import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, copyFileSync } from "node:fs";
import path from "node:path";
if (process.platform !== "win32") process.exit(0);
const root = process.cwd();
const vswhere = path.join(process.env["ProgramFiles(x86)"] || "C:/Program Files (x86)", "Microsoft Visual Studio/Installer/vswhere.exe");
const install = execFileSync(vswhere, ["-latest", "-products", "*", "-requires", "Microsoft.VisualStudio.Component.VC.Tools.x86.x64", "-property", "installationPath"], { encoding: "utf8" }).trim();
const version = execFileSync(vswhere, ["-latest", "-products", "*", "-requires", "Microsoft.VisualStudio.Component.VC.Tools.x86.x64", "-property", "installationVersion"], { encoding: "utf8" }).trim();
const cmake = path.join(install, "Common7/IDE/CommonExtensions/Microsoft/CMake/CMake/bin/cmake.exe");
if (!existsSync(cmake)) throw new Error("Visual Studio C++ CMake tools are required to build project thumbnails.");
const major = version.split(".")[0];
const generator = { "17": "Visual Studio 17 2022", "18": "Visual Studio 18 2026" }[major];
if (!generator) throw new Error(`Unsupported Visual Studio: ${version}`);
const source = path.join(root, "electron/native/project-thumbnail");
const build = path.join(source, "build", `vs${major}`);
execFileSync(cmake, ["-S", source, "-B", build, "-G", generator, "-A", process.arch === "arm64" ? "ARM64" : "x64"], { stdio: "inherit" });
execFileSync(cmake, ["--build", build, "--config", "Release"], { stdio: "inherit" });
const output = path.join(root, "electron/native/bin", process.arch === "arm64" ? "win32-arm64" : "win32-x64");
mkdirSync(output, { recursive: true });
copyFileSync(path.join(build, "Release/LeadCutThumbnail.dll"), path.join(output, "LeadCutThumbnail.dll"));
console.log("Built stream-based LeadCut project thumbnail provider.");
